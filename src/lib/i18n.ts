const allTranslations: Record<string, Record<string, unknown>> = { en: translations.en, es };

let currentLanguage: Language = 'en';

try {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('app-language') as Language;
    if (stored === 'en' || stored === 'es') {
      currentLanguage = stored;
    }
  }
} catch {
  // ignore
}

type Listener = () => void;
const listeners: Listener[] = [];

export function subscribe(listener: Listener): () => void {
  listeners.push(listener);
  return () => {
    const index = listeners.indexOf(listener);
    if (index > -1) listeners.splice(index, 1);
  };
}

function notifyListeners() {
  for (const listener of listeners) listener();
}

export function setLanguage(lang: Language) {
  currentLanguage = lang;
  if (typeof window !== 'undefined') {
    localStorage.setItem('app-language', lang);
  }
  notifyListeners();
}

export function getLanguage(): Language {
  return currentLanguage;
}

export function getServerLanguage(): Language {
  return 'en';
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const keys = key.split('.');
  let value: unknown = allTranslations[currentLanguage] || allTranslations['en'];

  for (const k of keys) {
    if (value && typeof value === 'object' && k in (value as Record<string, unknown>)) {
      value = (value as Record<string, unknown>)[k];
    } else {
      return key;
    }
  }

  if (typeof value !== 'string') {
    return key;
  }

  if (vars) {
    return value.replace(/\{\{(\w+)\}\}/g, (_, varName) => String(vars[varName] ?? `{{${varName}}}`));
  }

  return value;
}
